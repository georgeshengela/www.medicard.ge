#!/usr/bin/env node
// Copies the app's doctor-summary renderer and its clinician copy into the web /app, so the printable
// cycle report on the web is the same document the app shares as a PDF.
//   mobile/src/lib/cycleDoctorSummaryI18n.js → server/public/app/js/vendor/cycleDoctorSummary.js
//   mobile/src/i18n/cycle/doctorSummary.js   → server/public/app/js/vendor/doctorSummaryCopy.js
// Run after changing either mobile file:  node scripts/sync-web-cycle-report.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'server', 'public', 'app', 'js', 'vendor');
mkdirSync(outDir, { recursive: true });
const banner = (src) => `// Generated by scripts/sync-web-cycle-report.mjs from ${src} — do not edit by hand.\n`;

const copySrc = 'mobile/src/i18n/cycle/doctorSummary.js';
const copy = readFileSync(join(root, copySrc), 'utf8');
if (/^import /m.test(copy)) throw new Error(`${copySrc} has imports — teach the sync script about them`);
writeFileSync(join(outDir, 'doctorSummaryCopy.js'), banner(copySrc) + copy);

const rendererSrc = 'mobile/src/lib/cycleDoctorSummaryI18n.js';
let renderer = readFileSync(join(root, rendererSrc), 'utf8');
const swaps = [
  ["from '../i18n/cycle/doctorSummary.js';", "from './doctorSummaryCopy.js';"],
  ["import { appLang } from '../i18n/locale.js';", "import { lang as webLang } from '../i18n.js';\n\nconst appLang = () => webLang;"],
];
for (const [from, to] of swaps) {
  if (!renderer.includes(from)) throw new Error(`${rendererSrc}: expected import not found: ${from}`);
  renderer = renderer.replace(from, to);
}
const leftover = renderer.match(/^import .* from '(?!\.\/doctorSummaryCopy\.js|\.\.\/i18n\.js).*';$/m);
if (leftover) throw new Error(`${rendererSrc}: unexpected import ${leftover[0]}`);
writeFileSync(join(outDir, 'cycleDoctorSummary.js'), banner(rendererSrc) + renderer);
console.log('wrote', outDir);
