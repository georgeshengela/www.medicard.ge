TERM = {10: 'ოქტომბრამდე', 11: 'ნოემბრამდე', 12: 'დეკემბრამდე'}


def week_range(mon, label=False):
    """'12–18 ოქტომბერს' (sentence) / '12–18 ოქტომბერი' (label); across months '26 ოქტომბრიდან 1 ნოემბრამდე'."""
    a = date.fromisoformat(mon)
    b = a + timedelta(days=6)
    if a.month == b.month:
        return f'{a.day}–{b.day} {(MONTH if label else MONTH_DAT)[a.month]}'
    if label:
        return f'{a.day} {MONTH[a.month][:3]} – {b.day} {MONTH[b.month][:3]}'
    return f'{a.day} {ABL[a.month]} {b.day} {TERM[b.month]}'


