  function getHelp(path) {
    if (!path) return null;
    const parts = String(path).split('.');
    let node = ADMIN_HELP;
    for (const p of parts) {
      if (!node || typeof node !== 'object') return null;
      node = node[p];
    }
    return node && typeof node === 'object' && node.title ? node : null;
  }

  function listHelpKeys(obj = ADMIN_HELP, prefix = '') {
    const keys = [];
    Object.entries(obj).forEach(([k, v]) => {
      const path = prefix ? `${prefix}.${k}` : k;
      if (v && typeof v === 'object' && v.title) keys.push(path);
      else if (v && typeof v === 'object') keys.push(...listHelpKeys(v, path));
    });
    return keys;
  }

  global.ADMIN_HELP = ADMIN_HELP;
  global.AdminHelp = { get: getHelp, keys: listHelpKeys, registry: ADMIN_HELP };
