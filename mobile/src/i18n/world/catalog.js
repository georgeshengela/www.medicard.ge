const WORLD_COPY_KEYS = Object.freeze(Object.keys(TEXT.ka));

function worldCopy(locale = 'ka') {
  const loc = LOCALES.includes(locale) ? locale : 'ka';
  const table = TEXT[loc] || TEXT.ka;
  return { ...table, locale: loc };
}

function worldCopyTables() {
  return TEXT;
}

function worldReasonText(locale, reasonCode) {
  const copy = worldCopy(locale);
  return copy[reasonCode] || copy.FOUNDATION_LEGACY;
}

