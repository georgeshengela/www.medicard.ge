const GARDEN_COPY_KEYS = Object.freeze(Object.keys(TEXT.ka));

function gardenCopy(locale = 'ka') {
  const loc = LOCALES.includes(locale) ? locale : 'ka';
  const table = TEXT[loc] || TEXT.ka;
  return { ...table, locale: loc };
}

function gardenCopyTables() {
  return TEXT;
}

function gardenReactionText(locale, key) {
  const copy = gardenCopy(locale);
  const map = {
    first_visit: copy.first_visit,
    empty: copy.empty_reaction,
    enough_energy_to_plant: copy.enough_energy_to_plant,
    insufficient_energy: copy.insufficient_energy,
    newly_planted_seed: copy.newly_planted_seed,
    first_sprout: copy.first_sprout,
    bloom: copy.bloom_reaction,
    radiant: copy.radiant_reaction,
    newly_unlocked_plot: copy.newly_unlocked_plot,
    returned_after_inactivity: copy.returned_after_inactivity,
    all_plots_occupied: copy.all_plots_occupied,
    stored_plant: copy.stored_plant,
    restored_plant: copy.restored_plant,
  };
  return map[key] || copy.waiting;
}

function gardenLockedPlotBody(locale, level) {
  const n = Number(level);
  if (locale === 'ka' && Number.isInteger(n)) {
    if (n === 5) return 'ეს ადგილი მე-5 დონეზე გაიხსნება.';
    if (n === 10) return 'ეს ადგილი მე-10 დონეზე გაიხსნება.';
    if (n === 20) return 'ეს ადგილი მე-20 დონეზე გაიხსნება.';
    if (n > 0) return `ეს ადგილი ${n} დონეზე გაიხსნება.`;
  }
  const fallback = Number.isFinite(n) ? String(n) : '';
  return String(gardenCopy(locale).lockedPlotBody).replace('{level}', fallback);
}

module.exports = { GARDEN_COPY_KEYS, gardenCopy, gardenCopyTables, gardenReactionText, gardenLockedPlotBody };
