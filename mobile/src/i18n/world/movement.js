const MOVEMENT_COPY_KEYS = Object.freeze(Object.keys(TEXT.ka));

function movementCopy(locale = 'ka') {
  const loc = LOCALES.includes(locale) ? locale : 'ka';
  const table = TEXT[loc] || TEXT.ka;
  return { ...table, locale: loc };
}

function movementCopyTables() {
  return TEXT;
}

function movementMediLine(locale, key) {
  const copy = movementCopy(locale);
  const map = {
    start: copy.mediStart,
    halfway: copy.mediHalfway,
    low_gps: copy.mediLowGps,
    reanchor: copy.mediReanchor,
    pause: copy.mediPause,
    background_return: copy.mediBackground,
    complete: copy.mediComplete,
    partial: copy.mediPartial,
    none: copy.mediNone,
  };
  return map[key] || copy.mediStart;
}

