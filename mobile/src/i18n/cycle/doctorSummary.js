function ruDays(n) {
  const abs = Math.abs(n) % 100;
  const n1 = abs % 10;
  if (abs > 10 && abs < 20) return 'дней';
  if (n1 === 1) return 'день';
  if (n1 >= 2 && n1 <= 4) return 'дня';
  return 'дней';
}

function ruWeeks(n) {
  const abs = Math.abs(n) % 100;
  const n1 = abs % 10;
  if (abs > 10 && abs < 20) return 'недель';
  if (n1 === 1) return 'неделя';
  if (n1 >= 2 && n1 <= 4) return 'недели';
  return 'недель';
}

function ruCycles(n) {
  const abs = Math.abs(n) % 100;
  const n1 = abs % 10;
  if (abs > 10 && abs < 20) return 'циклов';
  if (n1 === 1) return 'цикл';
  if (n1 >= 2 && n1 <= 4) return 'цикла';
  return 'циклов';
}

/** Genitive after „из N“ / „последние N“: 1, 21… → цикла, otherwise циклов. */
function ruCyclesGen(n) {
  const abs = Math.abs(n) % 100;
  return abs % 10 === 1 && abs !== 11 ? 'цикла' : 'циклов';
}

